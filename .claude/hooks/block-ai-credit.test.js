test("inherited identity env counts", () => {
  const input = JSON.stringify({ tool_name: "Bash", tool_input: { command: "git commit -m x" }, cwd: human });
  assert.strictEqual(run(input, { GIT_AUTHOR_NAME: "Claude" }).status, 2);
});

test("MCP git tool args are scanned", () => {
  const call = (tool_name, message) => run(JSON.stringify({ tool_name, tool_input: { message }, cwd: human })).status;
  assert.strictEqual(call("mcp__github__create_pull_request", "Generated with Claude"), 2);
  assert.strictEqual(call("mcp__plugin_gitkraken_gitkraken__git_commit", "Co-Authored-By: Claude"), 2);
  assert.strictEqual(call("mcp__github__create_pull_request", "normal"), 0);
  assert.strictEqual(call("mcp__slack__send", "Generated with Claude"), 0);
});

test("unparseable or unexpected input exits 0", () => {
  for (const s of ["", "not json", "null", "{}", '{"tool_name":"Bash"}']) assert.strictEqual(run(s).status, 0, s);
});
