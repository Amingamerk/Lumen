const { test, after } = require("node:test");
const assert = require("node:assert");
const { spawnSync, execFileSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const HOOK = path.join(__dirname, "block-ai-credit.js");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "hooktest-"));
after(() => fs.rmSync(tmp, { recursive: true, force: true }));

// Isolate from global/system git config and inherited identity.
const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !/^(GIT_|EMAIL$)/i.test(k)));
env.GIT_CONFIG_GLOBAL = path.join(tmp, "gitconfig");
env.GIT_CONFIG_NOSYSTEM = "1";
fs.writeFileSync(env.GIT_CONFIG_GLOBAL, "");

function repo(dirName, { name = "Test Person", branch = "main", author } = {}) {
  const dir = path.join(tmp, dirName);
  fs.mkdirSync(dir, { recursive: true });
  const git = (...a) => execFileSync("git", a, { cwd: dir, env, stdio: "pipe" });
  git("init", "-q");
  git("symbolic-ref", "HEAD", "refs/heads/" + branch);
  git("config", "user.name", name);
  git("config", "user.email", "test@example.com");
  git("commit", "-q", "--allow-empty", "-m", "init", ...(author ? ["--author", author] : []));
  return dir;
}

const human = repo("human");
const botConfig = repo("botconfig", { name: "Claude" });
const botHead = repo("bothead", { author: "Claude <bot@example.com>" });
const onBranch = repo("onbranch", { branch: "claude/work" });
const pathOnly = repo("claude-tools", { branch: "chore/claude-hook" });
const noIdent = path.join(tmp, "noident");
fs.mkdirSync(noIdent);
execFileSync("git", ["init", "-q"], { cwd: noIdent, env });
execFileSync("git", ["config", "user.useConfigOnly", "true"], { cwd: noIdent, env });
fs.writeFileSync(path.join(human, "bad.txt"), "feat: x\n\nCo-Authored-By: Claude <x@y.z>\n");
fs.writeFileSync(path.join(human, "good msg.txt"), "feat: x\n");

const slash = (p) => p.replace(/\\/g, "/");
const run = (stdin, extraEnv) =>
  spawnSync(process.execPath, [HOOK], { input: stdin, env: { ...env, ...extraEnv }, encoding: "utf8" });
const hook = (command, cwd = human, tool = "Bash") =>
  run(JSON.stringify({ tool_name: tool, tool_input: { command }, cwd }));

function cases(title, status, list) {
  for (const [command, cwd = human, tool = "Bash"] of list) {
    test(`${title}: ${tool}: ${command.replaceAll(slash(tmp), "TMP").replace(/\n/g, "\\n")}`, () => {
      const r = hook(command, cwd, tool);
      assert.strictEqual(r.status, status, r.stderr);
      if (status === 2) assert.match(r.stderr, /^Blocked:/);
    });
  }
}

